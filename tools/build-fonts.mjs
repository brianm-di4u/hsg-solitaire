// Inline the vendored OFL fonts (vendor/fonts/*.woff2) into assets/fonts.css as data URIs.
// Chrome blocks @font-face loads from file:// URLs, so the fonts travel inside the stylesheet,
// which a plain <link rel="stylesheet"> can load from file:// and http alike.
// Run: node games/solitaire/tools/build-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const GAME = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(GAME, 'vendor', 'fonts');
const FACES = [
  ['Limelight', 400, 'limelight-latin-400-normal.woff2'],
  ['Josefin Sans', 400, 'josefin-sans-latin-400-normal.woff2'],
  ['Josefin Sans', 600, 'josefin-sans-latin-600-normal.woff2'],
  ['Josefin Sans', 700, 'josefin-sans-latin-700-normal.woff2'],
  ['Libre Bodoni', 700, 'libre-bodoni-latin-700-normal.woff2'],
];
let css = '/* Generated by tools/build-fonts.mjs from vendor/fonts (SIL Open Font License 1.1). Do not edit. */\n';
for (const [family, weight, file] of FACES) {
  const b64 = fs.readFileSync(path.join(SRC, file)).toString('base64');
  css += `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:swap;` +
    `src:url(data:font/woff2;base64,${b64}) format("woff2")}\n`;
}
fs.writeFileSync(path.join(GAME, 'assets', 'fonts.css'), css);
console.log('assets/fonts.css', (css.length / 1024).toFixed(1), 'KB');
